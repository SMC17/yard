// Naval code generation from spiral-optimized design parameters.
//
// Emits a compilable Zig module skeleton that imports yard primitives
// for time-domain simulation — "naval compilation" from high-level specs.

const std = @import("std");
const orchestrator = @import("orchestrator.zig");

pub const Error = error{OutOfMemory};

/// Generate Zig source for a vessel-specific simulator skeleton.
pub fn generateNavalCode(
    allocator: std.mem.Allocator,
    params: orchestrator.DesignParameters,
    vessel_name: []const u8,
) Error![]u8 {
    return std.fmt.allocPrint(allocator,
        \\// Auto-generated by yard-spiral — Evans design spiral output.
        \\// Vessel: {s}
        \\// L={d:.1} m, B={d:.1} m, T={d:.1} m, GM={d:.2} m, P_E≈{d:.0} kW
        \\
        \\const std = @import("std");
        \\const fossen = @import("yard_fossen");
        \\const resistance = @import("yard_resistance");
        \\
        \\pub const VesselSpec = struct {{
        \\    pub const L: f64 = {d};
        \\    pub const B: f64 = {d};
        \\    pub const T: f64 = {d};
        \\    pub const service_speed: f64 = {d};
        \\    pub const gm_m: f64 = {d};
        \\    pub const power_kw: f64 = {d};
        \\}};
        \\
        \\pub fn initState() fossen.fossen.State {{
        \\    return .{{
        \\        .eta = .{{ 0, 0, 0, 0, 0, 0 }},
        \\        .nu = .{{ VesselSpec.service_speed, 0, 0, 0, 0, 0 }},
        \\    }};
        \\}}
        \\
        \\pub fn step(state: fossen.fossen.State, tau: [6]f64, dt: f64) !fossen.fossen.State {{
        \\    const p = fossen.fossen.Parameters{{
        \\        .M_diag = .{{ 1e6, 1e6, 1e6, 1e7, 1e7, 1e7 }},
        \\        .D_lin = .{{ 1e4, 1e4, 1e4, 1e5, 1e5, 1e5 }},
        \\        .K_z = 1e6,
        \\        .K_phi = 1e7,
        \\        .K_theta = 1e7,
        \\    }};
        \\    return fossen.fossen.rk4Step(state, p, tau, dt);
        \\}}
        \\
    ,
        .{
            vessel_name,
            params.length,
            params.beam,
            params.draft,
            params.gm_m,
            params.estimated_power_kw,
            params.length,
            params.beam,
            params.draft,
            params.service_speed,
            params.gm_m,
            params.estimated_power_kw,
        },
    );
}

test "generateNavalCode contains vessel name and dimensions" {
    const code = try generateNavalCode(std.testing.allocator, .{
        .length = 100.0,
        .beam = 16.0,
        .draft = 6.0,
        .displacement = 8.0e6,
        .service_speed = 8.0,
        .gm_m = 1.2,
        .estimated_power_kw = 4500.0,
    }, "TestHull");
    defer std.testing.allocator.free(code);
    try std.testing.expect(std.mem.indexOf(u8, code, "TestHull") != null);
    try std.testing.expect(std.mem.indexOf(u8, code, "yard_fossen") != null);
}